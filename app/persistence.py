"""持久化仓储接口：把"业务要什么"和"数据库怎么写"分开。

**接口是异步的**：两种实现都必须提供协程函数。原因是同步 DB 调用会阻塞事件
循环——一次慢查询会把所有 SSE 连接和其他任务一起冻住。SQLite 没有官方异步
驱动，所以那边用 `asyncio.to_thread` 把具体执行丢进线程池，接口保持一致。

文档 §9.1 要求"正式上线前把 SQL 与业务逻辑隔离为仓储接口，并准备 SQLite 到
PostgreSQL 的迁移脚本"。这里定义接口，两个实现都满足它：

- `app.pg_store.PostgresStore`：PostgreSQL + 异步连接池（**唯一实现**）。

SQLite 实现已删除：两套实现意味着两套行为、两套测试、两种排障路径，而正式部署
本来就只有 PostgreSQL。本地开发也直接连本机 PG（`DATABASE_URL`），不再有"开发用
SQLite、线上用 PG"的分叉。

`open_store()` 在仓储层暴露，业务代码只认 `Repository` 协议；换实现前先用
`check_repository()` 校验（方法齐备 + 都是协程函数）。
"""
import inspect
from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class Repository(Protocol):
    """中台持久化需要的能力集合。

    只列出**执行内核真正用到**的方法，不做通用 ORM。字段形状以返回的 dict
    为准，避免业务层依赖具体数据库的行对象。
    """

    # ---- 会话与消息 ----
    async def ensure_session(self, session_id: str, **kwargs: Any) -> None: ...
    async def session(self, session_id: str) -> dict | None: ...
    async def append_message(self, session_id: str, role: str, content: str,
                       **kwargs: Any) -> None: ...
    async def messages(self, session_id: str) -> list[dict]: ...
    async def messages_after(self, session_id: str, after_id: int) -> list[dict]: ...
    async def list_sessions(self, limit: int = 50, **kwargs: Any) -> list[dict]: ...
    async def memory(self, session_id: str) -> dict: ...
    async def set_memory(self, session_id: str, *, summary: str, facts: dict,
                   upto: int) -> None: ...

    # ---- 任务与运行 ----
    async def create_task(self, task_id: str, session_id: str, message: str) -> None: ...
    async def task(self, task_id: str) -> dict | None: ...
    async def update_task(self, task_id: str, **fields: Any) -> None: ...
    async def create_run(self, run_id: str, task_id: str, **kwargs: Any) -> None: ...
    async def run(self, run_id: str) -> dict | None: ...
    async def update_run(self, run_id: str, **fields: Any) -> None: ...
    async def claim_run(self, worker_id: str, lease_seconds: float = 60.0,
                  now_ts: float | None = None,
                  run_id: str | None = None) -> dict | None: ...
    async def renew_lease(self, run_id: str, worker_id: str,
                    lease_seconds: float = 60.0) -> bool: ...
    async def release_lease(self, run_id: str, worker_id: str) -> None: ...

    # ---- 计划与步骤 ----
    async def save_plan(self, run_id: str, version: int, *, goal: str,
                  steps: list[dict], reason: str = '') -> None: ...
    async def plan(self, run_id: str, version: int | None = None) -> dict | None: ...
    async def save_steps(self, run_id: str, plan_version: int,
                   steps: list[dict]) -> None: ...
    async def steps_of(self, run_id: str, plan_version: int | None = None) -> list[dict]: ...
    async def update_step(self, run_id: str, plan_version: int, step_id: str,
                    **fields: Any) -> None: ...

    # ---- 动作账本 ----
    async def create_action(self, action_id: str, **kwargs: Any) -> dict: ...
    async def action(self, action_id: str) -> dict | None: ...
    async def find_action(self, idempotency_key: str) -> dict | None: ...
    async def update_action(self, action_id: str, **fields: Any) -> None: ...
    async def add_attempt(self, attempt_id: str, action_id: str) -> None: ...
    async def finish_attempt(self, attempt_id: str, *, error_type: str | None = None,
                       result_ref: str | None = None) -> None: ...
    async def attempts_of(self, action_id: str) -> list[dict]: ...

    # ---- 产物 ----
    async def add_artifact(self, artifact_id: str, **kwargs: Any) -> None: ...
    async def artifact(self, artifact_id: str) -> dict | None: ...

    # ---- 长期记忆 ----
    async def remember(self, **kwargs: Any) -> str | None: ...
    async def recall(self, scope_type: str, scope_id: str) -> list[dict]: ...
    async def forget(self, **kwargs: Any) -> int: ...

    # ---- 身份与登录会话（app/ticket_auth.py / app/auth.py） ----
    async def bind_identity(self, provider: str, subject: str, **kwargs: Any) -> dict: ...
    async def redeem_ticket(self, **kwargs: Any) -> dict: ...
    async def auth_session(self, token_digest: str) -> dict | None: ...
    async def revoke_auth_session(self, auth_session_id: str) -> bool: ...
    async def revoke_user_sessions(self, user_id: str) -> int: ...
    async def purge_auth_sessions(self, before_ts: float | None = None) -> int: ...

    # ---- 恢复与后台任务 ----
    async def reconcile_orphan_runs(self, owner: str | None = None,
                              now_ts: float | None = None) -> dict: ...
    async def enqueue_job(self, job_id: str, kind: str, dedupe_key: str,
                    payload: dict | None = None) -> bool: ...
    async def claim_job(self, worker_id: str, lease_seconds: float = 60.0,
                  now_ts: float | None = None) -> dict | None: ...
    async def finish_job(self, job_id: str, *, error: str | None = None,
                   retry: bool = False) -> None: ...

    # ---- 请求幂等（POST /api/tasks） ----
    async def reserve_request_key(self, scope_key: str, *, client_key: str,
                            tenant_id: str, owner_user_id: str,
                            endpoint: str, fingerprint: str,
                            expires_at: float) -> dict: ...
    async def request_key(self, scope_key: str) -> dict | None: ...
    async def complete_request_key(self, scope_key: str, response: dict, *,
                             task_id: str = '', session_id: str = '',
                             run_id: str = '') -> None: ...
    async def release_request_key(self, scope_key: str) -> None: ...
    async def purge_request_keys(self, now_ts: float | None = None) -> int: ...


def check_repository(candidate: object) -> list[str]:
    """检查某个实现是否满足仓储接口，返回**不满足**的方法名。

    两条要求，缺一不可：
    1. 方法存在且可调用；
    2. 方法必须是**协程函数**——同步实现在异步调用点会返回一个没人 await 的
       协程，表现成"调用了但什么都没发生"，最难查。

    用它给"换实现"上保险：新增实现先跑这个，问题立刻暴露。
    """
    missing = []
    for name in dir(Repository):
        if name.startswith('_'):
            continue
        expected = getattr(Repository, name, None)
        if not callable(expected):
            continue
        actual = getattr(candidate, name, None)
        if not callable(actual):
            missing.append(name)
            continue
        # 接口声明是 async def → 实现也必须是（SQLite 那边是 async 外壳）
        if inspect.iscoroutinefunction(expected) and not inspect.iscoroutinefunction(actual):
            missing.append(f'{name}（实现不是 async）')
    return sorted(missing)


def open_store(database_url: str | None = None):
    """返回仓储实现（只有 PostgreSQL 一种）。

    `DATABASE_URL` 未配置时直接报错，而不是悄悄退回一个本地文件库——"看起来能跑
    但数据在别处"是最难查的一类环境问题。
    """
    from app.config import settings
    from app.pg_store import PostgresStore

    url = (settings.database_url if database_url is None else database_url).strip()
    if not url:
        raise RuntimeError('未配置 DATABASE_URL。本项目只支持 PostgreSQL，'
                           '请在 .env 里给出 postgresql://... 连接串')
    if not url.startswith(('postgresql://', 'postgres://')):
        raise RuntimeError(f'DATABASE_URL 必须是 PostgreSQL 连接串，当前是 {url[:16]}…')
    return PostgresStore(url)
