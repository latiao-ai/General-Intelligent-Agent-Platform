"""持久化仓储接口：把"业务要什么"和"数据库怎么写"分开。

文档 §9.1 要求"正式上线前把 SQL 与业务逻辑隔离为仓储接口，并准备 SQLite 到
PostgreSQL 的迁移脚本"。这里定义接口，`app.store.Store` 是当前的 SQLite 实现。

**PostgresStore 尚未实现**。原因很直接：本开发环境没有 PostgreSQL 实例，
写一个不能运行的实现只会制造"看起来支持了"的假象。所以这一层只交付：

1. 明确的接口（Protocol），业务代码可以面向它编程；
2. SQLite 实现，已通过测试；
3. 迁移脚本 `scripts/migrate_to_postgres.py`（同样未在真实 PG 上验证）。

接 PostgreSQL 时新增一个满足同一 Protocol 的实现即可，调用方不用改。
"""
from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class Repository(Protocol):
    """中台持久化需要的能力集合。

    只列出**执行内核真正用到**的方法，不做通用 ORM。字段形状以返回的 dict
    为准，避免业务层依赖具体数据库的行对象。
    """

    # ---- 会话与消息 ----
    def append_message(self, session_id: str, role: str, content: str) -> None: ...
    def messages(self, session_id: str) -> list[dict]: ...
    def messages_after(self, session_id: str, after_id: int) -> list[dict]: ...
    def list_sessions(self, limit: int = 50) -> list[dict]: ...
    def memory(self, session_id: str) -> dict: ...
    def set_memory(self, session_id: str, *, summary: str, facts: dict,
                   upto: int) -> None: ...

    # ---- 任务与运行 ----
    def create_task(self, task_id: str, session_id: str, message: str) -> None: ...
    def task(self, task_id: str) -> dict | None: ...
    def update_task(self, task_id: str, **fields: Any) -> None: ...
    def create_run(self, run_id: str, task_id: str, **kwargs: Any) -> None: ...
    def run(self, run_id: str) -> dict | None: ...
    def update_run(self, run_id: str, **fields: Any) -> None: ...
    def claim_run(self, worker_id: str, lease_seconds: float = 60.0,
                  now_ts: float | None = None) -> dict | None: ...
    def renew_lease(self, run_id: str, worker_id: str,
                    lease_seconds: float = 60.0) -> bool: ...

    # ---- 计划与步骤 ----
    def save_plan(self, run_id: str, version: int, *, goal: str,
                  steps: list[dict], reason: str = '') -> None: ...
    def plan(self, run_id: str, version: int | None = None) -> dict | None: ...
    def save_steps(self, run_id: str, plan_version: int,
                   steps: list[dict]) -> None: ...
    def steps_of(self, run_id: str, plan_version: int | None = None) -> list[dict]: ...
    def update_step(self, run_id: str, plan_version: int, step_id: str,
                    **fields: Any) -> None: ...

    # ---- 动作账本 ----
    def create_action(self, action_id: str, **kwargs: Any) -> dict: ...
    def action(self, action_id: str) -> dict | None: ...
    def find_action(self, idempotency_key: str) -> dict | None: ...
    def update_action(self, action_id: str, **fields: Any) -> None: ...
    def add_attempt(self, attempt_id: str, action_id: str) -> None: ...
    def finish_attempt(self, attempt_id: str, *, error_type: str | None = None,
                       result_ref: str | None = None) -> None: ...
    def attempts_of(self, action_id: str) -> list[dict]: ...

    # ---- 产物 ----
    def add_artifact(self, artifact_id: str, **kwargs: Any) -> None: ...
    def artifact(self, artifact_id: str) -> dict | None: ...

    # ---- 长期记忆 ----
    def remember(self, **kwargs: Any) -> str | None: ...
    def recall(self, scope_type: str, scope_id: str) -> list[dict]: ...
    def forget(self, **kwargs: Any) -> int: ...

    # ---- 恢复与后台任务 ----
    def reconcile_orphan_runs(self) -> dict: ...
    def enqueue_job(self, job_id: str, kind: str, dedupe_key: str,
                    payload: dict | None = None) -> bool: ...
    def claim_job(self, worker_id: str, lease_seconds: float = 60.0,
                  now_ts: float | None = None) -> dict | None: ...
    def finish_job(self, job_id: str, *, error: str | None = None) -> None: ...


def check_repository(candidate: object) -> list[str]:
    """检查某个实现是否满足仓储接口，返回缺失的方法名。

    用它给"换实现"上保险：新增 PostgresStore 时先跑这个，缺方法立刻暴露，
    而不是等线上某条路径踩空。
    """
    missing = []
    for name in dir(Repository):
        if name.startswith('_'):
            continue
        if not callable(getattr(Repository, name, None)):
            continue
        if not callable(getattr(candidate, name, None)):
            missing.append(name)
    return sorted(missing)
